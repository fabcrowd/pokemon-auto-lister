#!/usr/bin/env node
/**
 * Write tools/extension-wasm/lib/set-totals.js: the printed card total of every
 * TCGdex set (cardCount.official), used to match "001/165" to its set.
 *
 *   node scripts/gen-set-totals.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'tools/extension-wasm/lib/set-totals.js');

const response = await fetch('https://api.tcgdex.net/v2/en/sets');
if (!response.ok) throw new Error(`TCGdex sets: HTTP ${response.status}`);
const sets = await response.json();

const totals = {};
for (const set of sets) {
  const official = set?.cardCount?.official;
  if (typeof set?.id === 'string' && Number.isInteger(official) && official > 0) totals[set.id] = official;
}
if (Object.keys(totals).length < 100) throw new Error(`TCGdex sets: only ${Object.keys(totals).length} usable sets`);

const body = Object.entries(totals).map(([id, total]) => `  ${JSON.stringify(id)}: ${total},`).join('\n');
await writeFile(OUT, `// Printed card total per set (TCGdex cardCount.official). Generated by scripts/gen-set-totals.mjs.\nexport const SET_TOTALS = {\n${body}\n};\n`);
console.log(`wrote ${Object.keys(totals).length} sets to ${path.relative(ROOT, OUT)}`);
